void main (){
  // For loop
  print("For Loop:");
  for (int i = 0; i < 5; i++) {
    print("Value of i: $i");
  }

  // While loop
  print("\nWhile Loop:");
  int j = 0;
  while (j < 5) {
    print("Value of j: $j");
    j++;
  }

  // Do-while loop
  print("\nDo-While Loop:");
  int k = 0;
  do {
    print("Value of k: $k");
    k++;
  } while (k < 5);
}